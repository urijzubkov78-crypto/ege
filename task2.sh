#!/bin/bash
# task2.sh

set -euo pipefail

echo "1. Перестановка столбцов (фамилия, имя, группа, оценка):"
# Убираем id и меняем порядок полей на: фамилия,имя,группа,оценка
sed -E '1s/.*/фамилия,имя,группа,оценка/; 2,$s/^[^,]+,([^,]+),([^,]+),([^,]+),([^,]+)$/\2,\1,\3,\4/' students.csv

echo -e "\n2. Фильтрация студентов группы ПИ-101:"
# Оставляем заголовок и записи только группы ПИ-101
sed -n -E '1p; /^([0-9]+),[^,]+,[^,]+,ПИ-101,[0-9.]+$/p' students.csv

echo -e "\n3. Замена оценок на категории:"
# Преобразуем 5.0 -> Отлично, 4.5-4.9 -> Хорошо, остальные -> Удовлетворительно
sed -E '1b; s/,5\.0$/,"Отлично"/; s/,4\.[5-9]$/,"Хорошо"/; t; s/,[0-9]+\.[0-9]+$/,"Удовлетворительно"/' students.csv

echo -e "\n4. Добавление заголовка в начало файла:"
# Добавляем строку "Список студентов" в начало потока
sed '1i\
Список студентов
' students.csv
